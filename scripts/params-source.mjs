// Pure: OpenAPI document → TypeScript source of the v3 command parameters (src/generated/v3-params.ts).

function resolveRef(spec, node) {
  let current = node;
  while (current && typeof current === "object" && typeof current.$ref === "string") {
    current = current.$ref
      .replace(/^#\//, "")
      .split("/")
      .reduce((value, key) => value?.[key], spec);
  }
  return current;
}

export function queryParams(spec, path) {
  const item = spec.paths[path];
  return [...(item.parameters ?? []), ...(item.get?.parameters ?? [])]
    .map((param) => resolveRef(spec, param))
    .filter((param) => param.in === "query")
    .map((param) => {
      const schema = resolveRef(spec, param.schema ?? {});
      return {
        name: param.name,
        required: param.required === true,
        type: schema.type,
        enum: schema.enum,
        minimum: schema.minimum,
        maximum: schema.maximum,
        default: schema.default,
        description: param.description ?? schema.description,
      };
    });
}

const SEVERAL_IDENTIFIERS_SENTENCE = /\s*If several identifiers are given[^.]*(?:\.|$)\s*/g;

function withDescription(param) {
  const text = param.description?.replace(SEVERAL_IDENTIFIERS_SENTENCE, " ").trim();
  const sentence = text && !/[.!?]$/.test(text) ? `${text}.` : text;
  return { ...param, description: sentence || undefined };
}

export function renderParams(spec) {
  const blocks = Object.keys(spec.paths).map((path) => {
    const lines = queryParams(spec, path).map((param) => `    ${JSON.stringify(withDescription(param))},`);
    return `  ${JSON.stringify(path)}: [\n${lines.join("\n")}\n  ],`;
  });
  return [
    `// Generated by scripts/generate-params.mjs from spec/v3-openapi.json (v3 API ${spec.info.version}) — do not edit; run \`npm run gen:params\`.`,
    ``,
    `export interface V3Param {`,
    `  name: string;`,
    `  required: boolean;`,
    `  type: string;`,
    `  enum?: readonly string[];`,
    `  minimum?: number;`,
    `  maximum?: number;`,
    `  default?: string | number;`,
    `  description?: string;`,
    `}`,
    ``,
    `export const v3Params = {`,
    ...blocks,
    `} as const satisfies Record<string, readonly V3Param[]>;`,
    ``,
    `export type V3Path = keyof typeof v3Params;`,
    ``,
  ].join("\n");
}
